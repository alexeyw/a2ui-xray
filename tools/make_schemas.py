#!/usr/bin/env python3
"""Build schemas.js from the A2UI v1.0 JSON Schemas.

Usage: python3 tools/make_schemas.py <dir with agent_to_renderer.json, common_types.json, catalog.json> [commit]

Sources (github.com/a2ui-project/a2ui, Apache License 2.0):
  specification/v1_0/json/agent_to_renderer.json
  specification/v1_0/json/common_types.json
  catalogs/basic/v1/catalog.json
Keyword-position "description", "title", "default", "examples" and the catalog's
"instructions" are dropped to keep the page small; property *names* are kept.
"""
import json, sys, pathlib

DROP = {"description", "title", "default", "examples", "instructions", "$comment"}
MAPS = {"properties", "$defs", "patternProperties", "components", "functions", "definitions"}

def strip(node, in_map=False):
    if isinstance(node, list):
        return [strip(x) for x in node]
    if not isinstance(node, dict):
        return node
    if in_map:  # keys are names, values are schemas
        return {k: strip(v) for k, v in node.items()}
    return {k: strip(v, k in MAPS) for k, v in node.items() if k not in DROP}

src = pathlib.Path(sys.argv[1])
commit = sys.argv[2] if len(sys.argv) > 2 else "unknown"
docs = {
    "agent": strip(json.loads((src / "agent_to_renderer.json").read_text())),
    "common": strip(json.loads((src / "common_types.json").read_text())),
    "basic": strip(json.loads((src / "catalog.json").read_text())),
}
out = pathlib.Path(__file__).resolve().parent.parent / "schemas.js"
out.write_text(
    "/* A2UI v1.0 JSON Schemas: specification/v1_0/json/agent_to_renderer.json, common_types.json and\n"
    f"   catalogs/basic/v1/catalog.json from https://github.com/a2ui-project/a2ui at commit {commit}.\n"
    "   Licensed under the Apache License 2.0 (https://www.apache.org/licenses/LICENSE-2.0).\n"
    "   Modified: descriptions, titles, defaults and instructions removed. Generated by tools/make_schemas.py. */\n"
    "globalThis.A2UI_SCHEMAS=" + json.dumps(docs, separators=(",", ":"), ensure_ascii=False) + ";\n"
)
print(out, out.stat().st_size, "bytes")
